var n1 = parseFloat(prompt("Digite o primeiro número:"));
var n2 = parseFloat(prompt("Digite o segundo número:"));

var resultado =
  "Soma: " + (n1 + n2) + "\n" +
  "Subtração: " + (n1 - n2) + "\n" +
  "Produto: " + (n1 * n2) + "\n" +
  "Divisão: " + (n1 / n2) + "\n" +
  "Resto: " + (n1 % n2);

alert(resultado);
